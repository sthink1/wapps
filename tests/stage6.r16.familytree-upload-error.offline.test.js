'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

// Inspect the installed complete source. Execute only the actual Multer
// configuration and final error middleware with isolated dependency doubles;
// do not require server.js or connect to MySQL, R2, or external APIs.
const filename = path.resolve(__dirname, '../routes/familyTree.js');
const source = fs.readFileSync(filename, 'utf8');
const begin = source.indexOf('// R16: mark only errors actually generated by our upload file filter.');
const end = source.indexOf('// Stage 6 R16: unexpected Family Tree failures', begin);
assert(begin >= 0 && end > begin, 'upload configuration not found');
const configCode = source.slice(begin, end);
const handlerStart = source.lastIndexOf('router.use((err, req, res, next) =>');
const handlerEnd = source.indexOf('\nmodule.exports = router;', handlerStart);
assert(handlerStart >= 0 && handlerEnd > handlerStart, 'final error middleware not found');
const handlerCode = source.slice(handlerStart, handlerEnd);
let middleware;
let uploadOptions;
class MulterError extends Error { constructor(code, message) { super(message || `Multer ${code}`); this.code = code; } }
const context = vm.createContext({
  multer: Object.assign(function(opts) {uploadOptions = opts; return { stub: true };}, {
    memoryStorage: () => ({ kind: 'memory-storage' }), MulterError
  }),
  router: { use: fn => {middleware = fn;} },
});
vm.runInContext(`${configCode}\n${handlerCode}`, context, {filename: 'familyTree-upload-extract.js'});
function filter(mimetype) {
  let record = null;
  uploadOptions.fileFilter({}, {mimetype}, (err, ok) => { record = {err, ok}; });
  assert(record, 'callback not called');
  return record;
}
function dispatch(error) {
  const record = {status: undefined, body: undefined, nextCalled: false, forwarded: undefined};
  const res = {status(status) {record.status=status; return this;},json(body) {record.body=body; return this;}};
  middleware(error, {}, res, err => {record.nextCalled = true; record.forwarded=err;});
  return record;
}

test('limits remain 10 MiB, memory storage remains enabled', () => {
  assert.equal(uploadOptions.limits.fileSize, 10 * 1024 * 1024);
  assert.equal(uploadOptions.storage.kind, 'memory-storage');
});
for (const mimetype of ['image/jpeg','image/png','image/webp']) {
  test(`approved image MIME ${mimetype} passes filter`, () => {
    const result=filter(mimetype);assert.equal(result.err,null);assert.equal(result.ok,true);
  });
}
test('rejected format retains exact HTTP 400 validation message', () => {
  const {err,ok}=filter('application/pdf');assert.equal(ok,false);
  const response=dispatch(err);assert.equal(response.status,400);
  assert.equal(response.body.message,'Only JPG, PNG, and WEBP images are allowed.');
  assert.equal(response.nextCalled,false);
});
test('Multer file-size exception retains HTTP 400 and original message', () => {
  const error=new MulterError('LIMIT_FILE_SIZE','File too large');
  const result=dispatch(error);
  assert.equal(result.status,400);assert.equal(result.body.message,'File too large');
});
test('other Multer upload error retains HTTP 400', () => {
  const result=dispatch(new MulterError('LIMIT_UNEXPECTED_FILE','Unexpected field'));
  assert.equal(result.status,400);assert.equal(result.body.message,'Unexpected field');
});
test('forged unexpected message containing Only JPG is forwarded unchanged', () => {
  const error=new Error('Only JPG: private DB information');
  const result=dispatch(error);
  assert.equal(result.nextCalled,true);assert.equal(result.forwarded,error);
  assert.equal(result.status,undefined);assert.equal(result.body,undefined);
});
test('unexpected exception with identical expected text is not accepted as validation', () => {
  const error=new Error('Only JPG, PNG, and WEBP images are allowed.');
  const result=dispatch(error);assert.equal(result.nextCalled,true);assert.equal(result.forwarded,error);
  assert.equal(result.status,undefined);
});
test('unexpected null errors are forwarded rather than dereferenced', () => {
  const result=dispatch(null);assert.equal(result.nextCalled,true);assert.equal(result.forwarded,null);
});
test('generic unexpected exception is forwarded unchanged', () => {
  const error=new Error('backend stack information');const result=dispatch(error);
  assert.equal(result.nextCalled,true);assert.equal(result.forwarded,error);
});
